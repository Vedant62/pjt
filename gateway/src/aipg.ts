import type { GatewayConfig } from "./config";

/**
 * Upstream client. In `live` mode this is a plain fetch to AIPG. In `mock` mode it returns a
 * synthetic `Response` with the same OpenAI-compatible shape (JSON or SSE stream), so the
 * gateway's request path is byte-for-byte the same in both modes. Mock mode never touches the network.
 */
export function makeUpstream(cfg: GatewayConfig) {
  async function chatCompletions(body: Record<string, unknown>, signal?: AbortSignal): Promise<Response> {
    if (cfg.aipgMode === "live") {
      return fetch(`${cfg.aipgBaseUrl}/v1/chat/completions`, {
        method: "POST",
        headers: { "content-type": "application/json", authorization: `Bearer ${cfg.aipgApiKey}` },
        body: JSON.stringify(body),
        signal,
      });
    }
    return mockCompletion(cfg, body, signal);
  }

  async function models(): Promise<unknown[] | null> {
    if (cfg.aipgMode !== "live") return null;
    try {
      const r = await fetch(`${cfg.aipgBaseUrl}/v1/models`, {
        headers: { authorization: `Bearer ${cfg.aipgApiKey}` },
        signal: AbortSignal.timeout(5000),
      });
      if (!r.ok) return null;
      const j = (await r.json()) as { data?: unknown[] };
      return j.data ?? null;
    } catch {
      return null;
    }
  }

  return { chatCompletions, models };
}

const CANNED =
  "This is a mock completion from the Cashew Gateway. No request was sent to AI Power Grid, so no credits were spent. " +
  "In live mode this text would be generated by a GPU worker on the grid serving the requested model. " +
  "Cashew checked your on-chain subscription before answering, metered this request, and will include it in the next " +
  "epoch's Merkle root so its inclusion can be verified on-chain.";

const sleep = (ms: number, signal?: AbortSignal) =>
  new Promise<void>((resolve, reject) => {
    if (ms <= 0) return resolve();
    const t = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => (clearTimeout(t), reject(new Error("aborted"))), { once: true });
  });

export function estimateTokens(text: string) {
  return Math.max(1, Math.ceil(text.length / 4));
}

function mockCompletion(cfg: GatewayConfig, body: Record<string, unknown>, signal?: AbortSignal): Response {
  const model = String(body.model);
  const messages = (body.messages as { role: string; content: unknown }[]) ?? [];
  const lastUser = [...messages].reverse().find((m) => m.role === "user");
  const echo = typeof lastUser?.content === "string" ? lastUser.content.slice(0, 80) : "";
  const text = (echo ? `You asked: "${echo}". ` : "") + CANNED;
  // One "token" per word-ish piece, capped at max_tokens.
  const maxTokens = Number(body.max_tokens ?? cfg.maxTokensCap);
  const pieces = (text.match(/\S+\s*/g) ?? []).slice(0, maxTokens);
  const promptTokens = messages.reduce((n, m) => n + 4 + estimateTokens(String(m.content ?? "")), 0);
  const usage = { prompt_tokens: promptTokens, completion_tokens: pieces.length, total_tokens: promptTokens + pieces.length };
  const id = `chatcmpl-mock-${Date.now().toString(36)}`;
  const created = Math.floor(Date.now() / 1000);
  const headers = { "x-grid-job-id": `mock-${id.slice(-8)}` };

  if (!body.stream) {
    const json = {
      id,
      object: "chat.completion",
      created,
      model,
      choices: [{ index: 0, message: { role: "assistant", content: pieces.join("") }, finish_reason: "stop" }],
      usage,
    };
    return new Response(
      new ReadableStream({
        async start(ctrl) {
          await sleep(cfg.mockTtftMs + cfg.mockTokenMs * pieces.length, signal).catch(() => {});
          ctrl.enqueue(new TextEncoder().encode(JSON.stringify(json)));
          ctrl.close();
        },
      }),
      { status: 200, headers: { ...headers, "content-type": "application/json" } },
    );
  }

  const enc = new TextEncoder();
  const sse = (o: unknown) => enc.encode(`data: ${JSON.stringify(o)}\n\n`);
  const chunk = (delta: object, finish: string | null = null) => ({
    id,
    object: "chat.completion.chunk",
    created,
    model,
    choices: [{ index: 0, delta, finish_reason: finish }],
  });
  const stream = new ReadableStream({
    async start(ctrl) {
      try {
        await sleep(cfg.mockTtftMs, signal);
        ctrl.enqueue(sse(chunk({ role: "assistant", content: "" })));
        for (const p of pieces) {
          ctrl.enqueue(sse(chunk({ content: p })));
          await sleep(cfg.mockTokenMs, signal);
        }
        ctrl.enqueue(sse(chunk({}, "stop")));
        const so = body.stream_options as { include_usage?: boolean } | undefined;
        if (so?.include_usage) ctrl.enqueue(sse({ id, object: "chat.completion.chunk", created, model, choices: [], usage }));
        ctrl.enqueue(enc.encode("data: [DONE]\n\n"));
        ctrl.close();
      } catch {
        ctrl.close();
      }
    },
  });
  return new Response(stream, { status: 200, headers: { ...headers, "content-type": "text/event-stream" } });
}

/** Incremental parser for OpenAI-style SSE: accumulates assistant content and the usage block. */
export class SseAccumulator {
  private buf = "";
  content = "";
  reasoning = "";
  usage: { prompt_tokens: number; completion_tokens: number } | null = null;

  push(text: string) {
    this.buf += text;
    let idx: number;
    while ((idx = this.buf.indexOf("\n")) >= 0) {
      const line = this.buf.slice(0, idx).trim();
      this.buf = this.buf.slice(idx + 1);
      if (!line.startsWith("data:")) continue;
      const data = line.slice(5).trim();
      if (!data || data === "[DONE]") continue;
      try {
        const j = JSON.parse(data);
        const d = j.choices?.[0]?.delta ?? {};
        if (typeof d.content === "string") this.content += d.content;
        const r = d.reasoning_content ?? d.reasoning;
        if (typeof r === "string") this.reasoning += r;
        if (j.usage && typeof j.usage.prompt_tokens === "number") this.usage = j.usage;
      } catch {
        /* partial or non-JSON line: ignore */
      }
    }
  }
}
