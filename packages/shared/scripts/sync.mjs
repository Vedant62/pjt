// Regenerates src/abis.ts and src/addresses.json from Foundry artifacts and deployments.
// Run after every deploy: `pnpm sync:abis`.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "../../../contracts");
const out = join(here, "../src");

const NAMES = ["MockUSDC", "PlanRegistry", "SubscriptionVault", "UsageRootRegistry"];
const lc = (s) => s[0].toLowerCase() + s.slice(1);

let abis = "// AUTO-GENERATED by packages/shared/scripts/sync.mjs — do not edit.\n\n";
for (const name of NAMES) {
  const art = JSON.parse(readFileSync(join(contracts, "out", `${name}.sol`, `${name}.json`), "utf8"));
  abis += `export const ${lc(name)}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(out, "abis.ts"), abis);

const depDir = join(contracts, "deployments");
const addresses = {};
for (const f of readdirSync(depDir).filter((f) => /^\d+\.json$/.test(f))) {
  const dep = JSON.parse(readFileSync(join(depDir, f), "utf8"));
  const seedPath = join(depDir, f.replace(".json", ".seed.json"));
  const seed = existsSync(seedPath) ? JSON.parse(readFileSync(seedPath, "utf8")) : {};
  addresses[dep.chainId] = {
    MockUSDC: dep.MockUSDC,
    PlanRegistry: dep.PlanRegistry,
    SubscriptionVault: dep.SubscriptionVault,
    UsageRootRegistry: dep.UsageRootRegistry,
    gateway: dep.gateway,
    deployer: dep.deployer,
    keeperFeeBps: dep.keeperFeeBps,
    startBlock: dep.startBlock,
    demoPlanId: seed.demoPlanId ?? null,
    prodPlanId: seed.prodPlanId ?? null,
  };
}
writeFileSync(join(out, "addresses.json"), JSON.stringify(addresses, null, 2) + "\n");
writeFileSync(
  join(out, "addresses.ts"),
  "// AUTO-GENERATED by packages/shared/scripts/sync.mjs — do not edit. Mirrors addresses.json.\n\nexport default " +
    JSON.stringify(addresses, null, 2) +
    ";\n",
);
console.log(`synced ABIs for ${NAMES.length} contracts; deployments for chains: ${Object.keys(addresses).join(", ")}`);
